use serde::Serialize;

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Cookie {
    pub name: String,
    pub value: String,
    pub domain: String,
    pub path: String,
    pub secure: bool,
    pub http_only: bool,
    pub expires: f64,
}

/// 从内嵌的 YouTube WebView2 会话中读取 Cookie（仅 Windows）。
#[cfg(windows)]
pub fn read_youtube_cookies(webview: &tauri::Webview) -> Result<Vec<Cookie>, String> {
    use std::sync::mpsc;
    use std::time::Duration;
    use webview2_com::GetCookiesCompletedHandler;
    use webview2_com::Microsoft::Web::WebView2::Win32::*;
    use windows::core::{HSTRING, PWSTR};
    use windows::Win32::System::Com::CoTaskMemFree;

    unsafe fn pwstr_value<F>(f: F) -> String
    where
        F: FnOnce(*mut PWSTR) -> windows::core::Result<()>,
    {
        let mut value = PWSTR::null();
        if f(&mut value).is_ok() {
            let text = value.to_string().unwrap_or_default();
            if !value.0.is_null() {
                CoTaskMemFree(Some(value.0 as *const _));
            }
            text
        } else {
            String::new()
        }
    }

    let (tx, rx) = mpsc::channel::<Result<Vec<Cookie>, String>>();
    let tx_err = tx.clone();

    webview
        .with_webview(move |platform| {
            let result = (|| -> Result<(), String> {
                let controller = platform.controller();
                let core = unsafe { controller.CoreWebView2() }.map_err(|e| e.to_string())?;
                let core2: ICoreWebView2_2 =
                    windows::core::Interface::cast(&core).map_err(|e| e.to_string())?;
                let manager = unsafe { core2.CookieManager() }.map_err(|e| e.to_string())?;
                let uri = HSTRING::from("https://www.youtube.com");
                let sink = tx.clone();
                let handler = GetCookiesCompletedHandler::create(Box::new(move |_hr, list| {
                    let mut out: Vec<Cookie> = Vec::new();
                    if let Some(list) = list {
                        unsafe {
                            let mut count: u32 = 0;
                            let _ = list.Count(&mut count);
                            for i in 0..count {
                                let Ok(c) = list.GetValueAtIndex(i) else {
                                    continue;
                                };
                                let name = pwstr_value(|p| c.Name(p));
                                let value = pwstr_value(|p| c.Value(p));
                                let domain = pwstr_value(|p| c.Domain(p));
                                let path = pwstr_value(|p| c.Path(p));
                                if name.is_empty() || domain.is_empty() {
                                    continue;
                                }
                                let mut secure = windows::core::BOOL(0);
                                let _ = c.IsSecure(&mut secure);
                                let mut http_only = windows::core::BOOL(0);
                                let _ = c.IsHttpOnly(&mut http_only);
                                let mut expires: f64 = 0.0;
                                let _ = c.Expires(&mut expires);
                                out.push(Cookie {
                                    name,
                                    value,
                                    domain,
                                    path: if path.is_empty() {
                                        "/".to_string()
                                    } else {
                                        path
                                    },
                                    secure: secure.as_bool(),
                                    http_only: http_only.as_bool(),
                                    expires,
                                });
                            }
                        }
                    }
                    let _ = sink.send(Ok(out));
                    Ok(())
                }));
                unsafe { manager.GetCookies(&uri, &handler) }
                    .map_err(|e| format!("读取 Cookie 失败: {e}"))
            })();
            if let Err(e) = result {
                let _ = tx_err.send(Err(e));
            }
        })
        .map_err(|e| format!("访问内置浏览器失败: {e}"))?;

    rx.recv_timeout(Duration::from_secs(8))
        .map_err(|_| "读取 Cookie 超时：请先在内置浏览器中打开并登录 YouTube".to_string())?
}

#[cfg(not(windows))]
pub fn read_youtube_cookies(_webview: &tauri::Webview) -> Result<Vec<Cookie>, String> {
    Err("当前平台暂不支持自动读取 Cookie".into())
}

/// 转换为 yt-dlp 可识别的 Netscape cookies.txt 内容
pub fn to_netscape(cookies: &[Cookie]) -> String {
    let mut lines = vec![
        "# Netscape HTTP Cookie File".to_string(),
        "# Generated by YT-Whisper Studio".to_string(),
        String::new(),
    ];
    for c in cookies {
        let mut domain = c.domain.clone();
        if !domain.starts_with('.') {
            domain = format!(".{domain}");
            // 不带点的一级域名（如 youtube.com）按 host-only 处理
            if c.domain.matches('.').count() == 1 {
                domain = c.domain.clone();
            }
        }
        let include_sub = if domain.starts_with('.') { "TRUE" } else { "FALSE" };
        let expires = if c.expires > 0.0 {
            c.expires.floor() as u64
        } else {
            0
        };
        let prefix = if c.http_only { "#HttpOnly_" } else { "" };
        lines.push(format!(
            "{}{}\t{}\t{}\t{}\t{}\t{}\t{}",
            prefix,
            domain,
            include_sub,
            if c.path.is_empty() { "/" } else { &c.path },
            if c.secure { "TRUE" } else { "FALSE" },
            expires,
            c.name,
            c.value
        ));
    }
    lines.push(String::new());
    lines.join("\r\n")
}
